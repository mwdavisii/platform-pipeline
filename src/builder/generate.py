"""Validate the spec, render every artifact, and write them with the lock."""

import json
import os
import stat
import tempfile
from pathlib import Path

from . import VERSION
from .config import load_base_images, load_platform, platform_sha256
from .errors import EXIT_INVALID, EXIT_NEEDS_INPUT, BuilderError
from .lock import LOCK_PATH, SPEC_PATH, build_lock, canonical_json, sha256_text
from .render.authz import render_authz
from .render.dockerfile import dockerignore, render_dockerfile
from .render.k8s import RESOURCES, render_k8s
from .spec import check_spec

MAX_LOCK_BYTES = 1_000_000


def render_all(spec: dict, root: Path, platform: dict, images: dict) -> dict[str, str]:
    files = {"Dockerfile": render_dockerfile(spec, root, VERSION, images), ".dockerignore": dockerignore(spec, root)}
    files.update(render_k8s(spec, platform, images[spec["app_type"]]["uid"]))
    if spec.get("authz"):
        files.update(render_authz(spec, platform))
    return dict(sorted(files.items()))


HEADER_PREFIXES = ("# Generated by builder", "// Generated by builder")
POLICY_FILE = "_platform/authz-policy.json"
# Every name the builder can ever emit under its own directories. Nothing else is ever deleted.
EMITTABLE = frozenset(
    [f"deploy/base/{name}" for name in (*RESOURCES, "kustomization.yaml")]
    + [f"_platform/{name}" for name in ("__init__.py", "authz.py", "entry.py", "authz.js", "authz-policy.json")]
)
BUILDER_DIRS = ("deploy", "deploy/base", "_platform")


def _fail(*errors, warnings=None):
    return BuilderError(EXIT_INVALID, errors=list(errors), warnings=warnings or [])


def _lstat(path: Path):
    try:
        return path.lstat()
    except FileNotFoundError:
        return None


def _check_layout(root: Path, outputs: list[str]) -> None:
    """Refuse before touching anything unless the builder's directories are real and every target is replaceable."""
    for rel in BUILDER_DIRS:
        st = _lstat(root / rel)
        if st is not None and not stat.S_ISDIR(st.st_mode):
            raise _fail(f"{rel} must be a real directory (not a link or file) so the builder can write there safely.")
    for rel in outputs:
        st = _lstat(root / rel)
        if st is not None and stat.S_ISDIR(st.st_mode):
            raise _fail(f"{rel} is a directory; the builder needs to write a file there.")


def _write(root: Path, rel: str, text: str) -> None:
    """Write via a temp file in the same directory and os.replace, so links and hardlinks are replaced, never written through."""
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".builder-tmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _previous_files(root: Path) -> dict:
    lock = root / LOCK_PATH
    try:
        st = lock.lstat()
        if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_LOCK_BYTES:
            return {}
        files = json.loads(lock.read_text(encoding="utf-8")).get("files", {})
    except (OSError, UnicodeDecodeError, ValueError, AttributeError, RecursionError):
        return {}
    return files if isinstance(files, dict) else {}


def _stale(root: Path, previous: dict, current: dict) -> list[str]:
    """Previously generated files that are no longer produced and are still exactly what the builder wrote."""
    stale = []
    for rel in sorted(set(previous) - set(current)):
        digest = previous[rel]
        if rel not in EMITTABLE or not isinstance(digest, str):
            continue
        path = root / rel
        try:
            st = path.lstat()
            if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_LOCK_BYTES:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if sha256_text(text) == digest and (rel == POLICY_FILE or text.startswith(HEADER_PREFIXES)):
            stale.append(rel)
    return stale


def generate(root: Path, spec: dict) -> dict:
    platform = load_platform()
    errors, questions, warnings = check_spec(spec, root, platform)
    if errors:
        raise BuilderError(EXIT_INVALID, errors=errors, warnings=warnings)
    if questions:
        raise BuilderError(EXIT_NEEDS_INPUT, questions=questions, warnings=warnings)

    files = render_all(spec, root, platform, load_base_images())
    lock = build_lock(spec, files, VERSION, platform_sha256())

    outputs = [*files, SPEC_PATH, LOCK_PATH]
    try:
        _check_layout(root, outputs)
        stale = _stale(root, _previous_files(root), files)
        for rel, text in files.items():
            _write(root, rel, text)
        _write(root, SPEC_PATH, canonical_json(spec))
        for rel in stale:
            (root / rel).unlink()
        _write(root, LOCK_PATH, canonical_json(lock))
    except OSError as exc:
        raise _fail(f"Generate failed and may be incomplete: {exc.strerror or type(exc).__name__}. Fix the problem and run it again.", warnings=warnings) from exc
    return {"files": [*files, SPEC_PATH, LOCK_PATH], "removed": stale, "lock": lock, "warnings": warnings}
