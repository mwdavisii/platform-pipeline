"""_platform/ files: the authz policy and the code that enforces it without editing user code."""

import json
from importlib import resources

PY_HEADER = "# Generated by builder. Do not edit by hand; change the authz block in builder-spec.json and run `builder generate`.\n"


def _template(name: str) -> str:
    return resources.files("builder").joinpath("data", "authz", name).read_text(encoding="utf-8")


def policy_json(spec: dict, platform: dict) -> str:
    authz = spec["authz"]
    policy = {
        "default": "deny",
        "identity_header": platform["identity_header"],
        "exempt_paths": [spec["health_path"]] if "health_path" in spec else [],
        "roles": authz["roles"],
        "rules": [{"methods": sorted(r["methods"]), "path": r["path"], "roles": sorted(r["roles"])} for r in authz["rules"]],
    }
    return json.dumps(policy, indent=2, sort_keys=True) + "\n"


def python_entry(spec: dict) -> str:
    module, attr = spec["entrypoint"].split(":")
    wrapper = "AuthzASGI" if spec["server"] == "uvicorn" else "AuthzWSGI"
    return f"{PY_HEADER}from _platform.authz import {wrapper}\nfrom {module} import {attr} as _inner\n\napp = {wrapper}(_inner)\n"


def render_authz(spec: dict, platform: dict) -> dict[str, str]:
    if spec["app_type"] == "static":
        raise ValueError("authz does not apply to static sites; protect them at the edge")
    files = {"_platform/authz-policy.json": policy_json(spec, platform)}
    if spec["app_type"] == "python":
        files["_platform/__init__.py"] = PY_HEADER
        files["_platform/authz.py"] = _template("authz.py.tmpl")
        files["_platform/entry.py"] = python_entry(spec)
    elif spec["app_type"] == "node":
        files["_platform/authz.js"] = _template("authz.js.tmpl")
    return files
