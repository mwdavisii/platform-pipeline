"""deploy/base manifests: PSS-restricted Deployment, edge-only ingress, Cilium FQDN egress."""

import copy

import yaml

HEADER = "# Generated by builder. Do not edit by hand; change builder-spec.json and run `builder generate`.\n"
RESOURCES = ["serviceaccount.yaml", "deployment.yaml", "service.yaml", "networkpolicy.yaml", "cilium-egress.yaml"]


def _dump(doc: dict) -> str:
    return HEADER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)


def _labels(spec: dict) -> dict:
    return {"app.kubernetes.io/name": spec["app_name"], "app.kubernetes.io/managed-by": "golden-road-builder"}


def _selector(spec: dict) -> dict:
    return {"app.kubernetes.io/name": spec["app_name"]}


def _probe(spec: dict) -> dict:
    if "health_path" in spec:
        return {"httpGet": {"path": spec["health_path"], "port": "http"}}
    if spec["app_type"] == "static":
        return {"httpGet": {"path": "/", "port": "http"}}
    return {"tcpSocket": {"port": "http"}}


def _env(spec: dict) -> list[dict]:
    name = spec["app_name"]
    env = [{"name": "PORT", "value": str(spec["port"])}]
    for var in spec["env"]:
        if var["secret"]:
            source = {"secretKeyRef": {"name": f"{name}-secrets", "key": var["name"]}}
        else:
            source = {"configMapKeyRef": {"name": f"{name}-config", "key": var["name"], "optional": True}}
        env.append({"name": var["name"], "valueFrom": source})
    return env


def deployment(spec: dict, platform: dict, uid: int) -> dict:
    name, probe = spec["app_name"], _probe(spec)
    container = {
        "name": "app",
        "image": name,
        "imagePullPolicy": "IfNotPresent",
        "ports": [{"name": "http", "containerPort": spec["port"], "protocol": "TCP"}],
        "env": _env(spec),
        "resources": platform["resources_tiers"][spec["resources_tier"]],
        "readinessProbe": {**copy.deepcopy(probe), "periodSeconds": 10},
        "livenessProbe": {**copy.deepcopy(probe), "initialDelaySeconds": 10, "periodSeconds": 20},
        "securityContext": {
            "allowPrivilegeEscalation": False,
            "readOnlyRootFilesystem": True,
            "runAsNonRoot": True,
            "capabilities": {"drop": ["ALL"]},
        },
        "volumeMounts": [{"name": "tmp", "mountPath": "/tmp"}],
    }
    return {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "labels": _labels(spec)},
        "spec": {
            "replicas": 1,
            "selector": {"matchLabels": _selector(spec)},
            "template": {
                "metadata": {"labels": {**_labels(spec), "platform/data-classification": spec["data_classification"]}},
                "spec": {
                    "serviceAccountName": name,
                    "automountServiceAccountToken": False,
                    "securityContext": {
                        "runAsNonRoot": True,
                        "runAsUser": uid,
                        "runAsGroup": uid,
                        "seccompProfile": {"type": "RuntimeDefault"},
                    },
                    "containers": [container],
                    "volumes": [{"name": "tmp", "emptyDir": {"sizeLimit": "64Mi"}}],
                },
            },
        },
    }


def service(spec: dict) -> dict:
    return {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": spec["app_name"], "labels": _labels(spec)},
        "spec": {"type": "ClusterIP", "selector": _selector(spec), "ports": [{"name": "http", "port": 80, "targetPort": "http", "protocol": "TCP"}]},
    }


def service_account(spec: dict) -> dict:
    return {
        "apiVersion": "v1",
        "kind": "ServiceAccount",
        "metadata": {"name": spec["app_name"], "labels": _labels(spec)},
        "automountServiceAccountToken": False,
    }


def network_policy(spec: dict, platform: dict) -> dict:
    """Ingress only from the edge connector. Empty egress is a portable default-deny; Cilium adds the allows."""
    edge = platform["edge_ingress"]
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "NetworkPolicy",
        "metadata": {"name": f"{spec['app_name']}-baseline", "labels": _labels(spec)},
        "spec": {
            "podSelector": {"matchLabels": _selector(spec)},
            "policyTypes": ["Ingress", "Egress"],
            "ingress": [
                {
                    "from": [
                        {
                            "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": edge["namespace"]}},
                            "podSelector": {"matchLabels": edge["pod_labels"]},
                        }
                    ],
                    "ports": [{"protocol": "TCP", "port": "http"}],
                }
            ],
            "egress": [],
        },
    }


def cilium_egress(spec: dict, platform: dict) -> dict:
    dns = platform["dns"]
    egress = [
        {
            "toEndpoints": [{"matchLabels": {"io.kubernetes.pod.namespace": dns["namespace"], **dns["pod_labels"]}}],
            "toPorts": [{"ports": [{"port": "53", "protocol": "ANY"}], "rules": {"dns": [{"matchPattern": "*"}]}}],
        }
    ]
    in_cluster = platform.get("in_cluster_egress", {})
    for entry in sorted(spec["egress"], key=lambda e: (e["host"], e["port"])):
        target = in_cluster.get(entry["host"])
        if target:
            # An in-cluster service has no public DNS name Cilium could pin, so select its pods instead.
            egress.append(
                {
                    "toEndpoints": [{"matchLabels": {"io.kubernetes.pod.namespace": target["namespace"], **target["pod_labels"]}}],
                    "toPorts": [{"ports": [{"port": str(target["port"]), "protocol": "TCP"}]}],
                }
            )
            continue
        egress.append(
            {
                "toFQDNs": [{"matchName": entry["host"]}],
                "toPorts": [{"ports": [{"port": str(entry["port"]), "protocol": "TCP"}]}],
            }
        )
    return {
        "apiVersion": "cilium.io/v2",
        "kind": "CiliumNetworkPolicy",
        "metadata": {"name": f"{spec['app_name']}-egress", "labels": _labels(spec)},
        "spec": {"endpointSelector": {"matchLabels": _selector(spec)}, "egress": egress},
    }


def render_k8s(spec: dict, platform: dict, uid: int) -> dict[str, str]:
    documents = {
        "serviceaccount.yaml": service_account(spec),
        "deployment.yaml": deployment(spec, platform, uid),
        "service.yaml": service(spec),
        "networkpolicy.yaml": network_policy(spec, platform),
        "cilium-egress.yaml": cilium_egress(spec, platform),
        "kustomization.yaml": {"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": RESOURCES},
    }
    return {f"deploy/base/{name}": _dump(doc) for name, doc in documents.items()}
