FLUX_DIR, ARGO_DIR = "clusters/home/flux", "clusters/office/argo"
ADAPTER_DIR_FILES = {FLUX_DIR: {"README.md", "gitrepository.yaml"}, ARGO_DIR: {"README.md"}}  # the committed, non-generated files
DEPLOY_REPO_URL = re.compile(r"^https://[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?/[A-Za-z0-9_-]+/golden-road-deploy$")
ADAPTER_HEADER = ("# Generated by golden-road compose; deploy-check fails on any edit. {what}\n"
                  "# Nothing reconciles from git: {how}\n")


def _rel(d: Path, name: str = "") -> str:
    """The directory (or a file in it) as a path from apps/, for messages."""
    path = "apps/" + "/".join(Path(d).parts[-3:])
    return f"{path}/{name}" if name else path


def default_namespace(repo: str, environment: str) -> str:
    """The namespace convention, one per environment: <repo>-<env>, the repo name lowercased with . and _ turned into - and
    leading or trailing - dropped. A repo whose name gives no valid DNS-1123 label (over 63 characters with the suffix, or no
    letters or digits) is refused: its namespace is chosen by hand in release.yaml."""
    if environment not in ENVIRONMENTS or not isinstance(repo, str) or repo.count("/") != 1:
        raise InputError(f"no namespace for {repo!r} in {environment!r}"[:300])
    name = re.sub(r"[._]", "-", repo.split("/")[1].lower()).strip("-")
    namespace = f"{name}-{environment}"
    if not name or not NAMESPACE.fullmatch(namespace):
        raise InputError(f"{repo}'s name gives no valid namespace ({namespace!r}); set release.yaml's namespace by hand"[:300])
    return namespace


def _scan(d: Path) -> list[str]:
    """Problems with the directory's shape: a symlink anywhere (the directory itself and its owner and repo parents included), or
    any path but the allowed ones. Never follows a symlink."""
    d = Path(d)
    for node in (d, d.parent, d.parent.parent):
        if node.is_symlink():
            return [f"{_rel(d)}: {_rel(node) if node == d else node.name} is a symlink"]
    if not d.is_dir():
        return [f"{_rel(d)} is not a directory"]
    problems, stack = [], [d]
    while stack:
        for path in sorted(stack.pop().iterdir()):
            rel = path.relative_to(d).as_posix()
            if path.is_symlink():
                problems.append(f"{_rel(d, rel)} is a symlink")
            elif rel not in ALLOWED:
                problems.append(f"{_rel(d, rel)} is not a file golden-road-deploy holds")
            elif path.is_dir():
                if rel != "base":
                    problems.append(f"{_rel(d, rel)} must be a file")
                else:
                    stack.append(path)
            elif rel == "base":
                problems.append(f"{_rel(d, rel)} must be a directory")
    return problems


def _read_capped(path: Path, max_bytes: int, label: str) -> bytes:
    """A regular file's bytes, at most max_bytes. Messages name the file as `label`, its path in the environment directory."""
    if path.is_symlink():
        raise InputError(f"{label} is a symlink")
    if not path.is_file():
        raise InputError(f"{label} must be a regular file")
    if path.stat().st_size > max_bytes:
        raise InputError(f"{label} is too large")
    return path.read_bytes()


def load_release(d) -> dict:
    """release.yaml: one YAML object, no anchors, at most 1 MB, a valid deploy-release/v1 whose repo and environment are exactly the
    directory's owner/repo/env (a name that differs, even only in case, is refused rather than guessed at)."""
    d = Path(d)
    path = d / "release.yaml"
    if path.is_symlink():
        raise InputError("release.yaml is a symlink")
    doc = _read_yaml(path, MAX_FILE_BYTES, loader=UniqueKeyLoader, label="release.yaml")
    errors = validate("deploy-release.v1", doc)
    if errors:
        raise InputError(f"release.yaml is not a valid deploy-release/v1: {errors[0]}"[:300])
    owner, repo, env = d.parts[-3:]
    if doc["repo"] != f"{owner}/{repo}":
        raise InputError(f"release.yaml's repo is {doc['repo']}, but its directory is apps/{owner}/{repo}")
    if doc["environment"] != env:
        raise InputError(f"release.yaml's environment is {doc['environment']}, but its directory is {env}")
    return doc


def load_binding_v2(d, release: dict):
    """bindings.yaml, or None when the environment has none: a valid binding/v2 for exactly the release's repo and environment."""
    path = Path(d) / "bindings.yaml"
    if path.is_symlink():
        raise InputError("bindings.yaml is a symlink")
    if not path.exists():
        return None
    doc = _read_yaml(path, MAX_BINDING_BYTES, loader=UniqueKeyLoader, label="bindings.yaml")
    if doc.get("schema") == "binding/v1":
        raise InputError("bindings in golden-road-deploy are binding/v2 (they name their environment); this is binding/v1")
    errors = validate("binding.v2", doc)
    if errors:
        raise InputError(f"bindings.yaml is not a valid binding/v2: {errors[0]}"[:300])
    if doc["repo"] != release["repo"]:
        raise InputError(f"bindings.yaml's repo is {doc['repo']}, not {release['repo']}")
    if doc["environment"] != release["environment"]:
        raise InputError(f"bindings.yaml's environment is {doc['environment']}, not {release['environment']}")
    return doc


def _reserved_secret_envs(binding) -> None:
    """A secret's env name is never one the builder reserves (PORT, PATH, NODE_OPTIONS, LD_*, AZURE_*, ...): compose refuses only the
    platform's own prefixes, because the portal holds compose byte for byte and can't import the builder; this catches the rest,
    including a bindings.yaml edited by hand."""
    for secret in (binding or {}).get("secrets") or []:
        why = reserved_reason(secret["env"])
        if why:
            raise InputError(f"bindings.yaml's secret env {secret['env']} is reserved: {why}"[:300])


def _generated(d: Path) -> tuple[dict, dict | None]:
    """({name: text} for the generated files, the binding they were composed from), from the files on disk. Raises InputError on
    anything refused."""
    release = load_release(d)
    binding = load_binding_v2(d, release)
    _reserved_secret_envs(binding)
    base = d / "base"
    if base.is_symlink():
        raise InputError("base is a symlink")
    raw = _read_capped(base / "manifests.yaml", MAX_FILE_BYTES, "base/manifests.yaml")
    if hashlib.sha256(raw).hexdigest() != release["manifests_sha256"]:
        raise InputError("base/manifests.yaml is not the release's manifests: its sha256 is not release.yaml's manifests_sha256")
    try:
        text = raw.decode("utf-8")
        return ({"composed.yaml": compose(text, release["image"], binding, namespace=release["namespace"]),
                 "kustomization.yaml": kustomization(release["namespace"])}, binding)
    except UnicodeDecodeError:
        raise InputError("base/manifests.yaml is not UTF-8") from None
    except ComposeError as exc:
        raise InputError(str(exc)) from None


def plan_environment(d) -> dict:
    """{path: text} for one environment directory's composed.yaml and kustomization.yaml, computed without writing. Refuses the
    directory on any problem verify_environment would report except the generated files being stale or missing."""
    d = Path(d)
    problems = _scan(d)
    if problems:
        raise InputError(problems[0])
    try:
        texts, _ = _generated(d)
    except InputError as exc:
        raise InputError(f"{_rel(d)}: {exc}") from None
    return {d / name: texts[name] for name in GENERATED}


def write_planned(planned: dict) -> list[Path]:
    for path, text in planned.items():
        Path(path).parent.mkdir(parents=True, exist_ok=True)  # clusters/home/flux and clusters/office/argo; plan_adapters refused symlinks
        write_text_atomic(path, text)
    return list(planned)


def compose_environment(d) -> list[Path]:
    """Write composed.yaml and kustomization.yaml for one environment directory; returns the two paths. Writes nothing when
    plan_environment refuses it."""
    return write_planned(plan_environment(d))


def _external_secret_problems(rel: str, composed: bytes, binding) -> list[str]:
    """Defence in depth beside the drift check: the ExternalSecret in composed.yaml, as committed, is exactly the object compose
    writes from the binding (the binding's secrets, from the platform's ClusterSecretStore, into the app's own Secret), and
    composed.yaml carries no store of its own. The specific problems name what differs; the whole-object comparison catches the rest."""
    try:
        objects = [o for o in yaml.load_all(composed.decode("utf-8"), Loader=UniqueKeyLoader) if o is not None]
    except (UnicodeDecodeError, yaml.YAMLError, RecursionError) as exc:
        return [f"{rel}: not YAML ({type(exc).__name__}), so its ExternalSecret can't be checked"]
    kinds = [o.get("kind") if isinstance(o, dict) else None for o in objects]
    problems = [f"{rel}: a {kind} is the platform's (external-secrets/), never an environment's"
                for kind in kinds if kind in ("SecretStore", "ClusterSecretStore")]
    found = [o for o in objects if isinstance(o, dict) and o.get("kind") == "ExternalSecret"]
    want = [(env, str(sid), slug) for env, sid, slug in effects(binding)["secrets"]]
    if len(found) > 1:
        return problems + [f"{rel}: {len(found)} ExternalSecrets; an environment's secrets make exactly one"]
    if not found:
        return problems + ([f"{rel}: the binding has secrets but there is no ExternalSecret"] if want else [])
    if not want:
        return problems + [f"{rel}: an ExternalSecret, but the binding has no secrets"]
    es = found[0]
    meta = es.get("metadata") if isinstance(es.get("metadata"), dict) else {}
    spec = es.get("spec") if isinstance(es.get("spec"), dict) else {}
    deployments = [o for o in objects if isinstance(o, dict) and o.get("kind") == "Deployment"]
    app = (deployments[0].get("metadata") or {}).get("name") if len(deployments) == 1 and isinstance(deployments[0].get("metadata"), dict) else None
    if not isinstance(app, str) or meta.get("name") != app + EXTERNAL_SECRET_SUFFIX:
        problems.append(f"{rel}: the ExternalSecret's name {str(meta.get('name'))[:80]!r} is not the app's (<deployment>{EXTERNAL_SECRET_SUFFIX})")
    if spec.get("secretStoreRef") != {"kind": "ClusterSecretStore", "name": EXTERNAL_SECRET_STORE}:
        problems.append(f"{rel}: the ExternalSecret's store is not ClusterSecretStore/{EXTERNAL_SECRET_STORE}, the platform's")
    target = spec.get("target") if isinstance(spec.get("target"), dict) else {}
    if target.get("name") != meta.get("name"):
        problems.append(f"{rel}: the ExternalSecret's target {str(target.get('name'))[:80]!r} is not its own name")
    data = spec.get("data")
    try:
        got = [(i["secretKey"], i["remoteRef"]["key"], i["remoteRef"]["property"]) for i in data] if isinstance(data, list) else None
    except (KeyError, TypeError):
        got = None
    if got is None:
        problems.append(f"{rel}: the ExternalSecret's data is not a list of secretKey and remoteRef key and property")
    elif got != want:
        extra = sorted({f"{k}={i}/{p}" for k, i, p in got} - {f"{k}={i}/{p}" for k, i, p in want}, key=str)
        problems.append(f"{rel}: the ExternalSecret's data is not the binding's secrets"
                        + (f" (not in the binding: {', '.join(str(e) for e in extra)})"[:300] if extra else ""))
    # The whole object, so nothing the specific checks don't name (dataFrom, target.template, metadata.namespace, apiVersion, an
    # extra key) can ride along: it is exactly what compose writes from the binding.
    if not problems and (not isinstance(app, str) or es != external_secret(app, effects(binding)["secrets"])):
        problems.append(f"{rel}: the ExternalSecret is not exactly what golden-road compose writes from the binding")
    return problems


def verify_environment(d) -> list[str]:
    """Every problem with one environment directory, as strings: its shape, its records, the base's hash, and generated files that
    are missing or differ from what compose_environment writes. Never writes."""
    d = Path(d)
    problems = _scan(d)
    if problems:
        return problems
    try:
        texts, binding = _generated(d)
    except (InputError, OSError) as exc:
        return [f"{_rel(d)}: {exc}"]
    for name in GENERATED:
        path, want = d / name, texts[name].encode("utf-8")
        if not path.is_file():
            problems.append(f"{_rel(d, name)} is missing; run golden-road compose")
        elif path.stat().st_size != len(want) or path.read_bytes() != want:
            problems.append(f"{_rel(d, name)} differs from what golden-road compose writes")
    composed = d / "composed.yaml"
    if composed.is_file() and composed.stat().st_size <= MAX_FILE_BYTES:
        problems += _external_secret_problems(_rel(d, "composed.yaml"), composed.read_bytes(), binding)
    return problems


def environment_dir(root, rel: str) -> Path:
    """An environment path given relative to the deploy repo's root: exactly apps/<owner>/<repo>/<test|prod>, nothing else."""
    if not isinstance(rel, str) or not ENVIRONMENT_PATH.fullmatch(rel) or any(part in (".", "..") for part in rel.split("/")):
        raise InputError(f"{rel!r} is not an environment path, apps/<owner>/<repo>/<test|prod>"[:300])
    apps = Path(root) / "apps"
    if apps.is_symlink():
        raise InputError("apps/ is a symlink")
    return Path(root) / rel


def find_environments(root) -> tuple[list[Path], list[str]]:
    """Every apps/<owner>/<repo>/<env> directory, and a problem for anything under apps/ that is not one (a file or a symlink at
    the wrong depth, an environment other than test or prod, one repo under two cases). apps/.gitkeep is allowed."""
    apps = Path(root) / "apps"
    if apps.is_symlink() or not apps.is_dir():
        raise InputError("the deploy repo has no apps/ directory")
    found, problems, repos = [], [], {}
    for owner in sorted(apps.iterdir()):
        rel = f"apps/{owner.name}"
        if owner.name == ".gitkeep" and owner.is_file() and not owner.is_symlink():
            continue
        if owner.is_symlink() or not owner.is_dir():
            problems.append(f"{rel} is {'a symlink' if owner.is_symlink() else 'not a directory'}; apps/ holds only apps/<owner>/<repo>/<env>")
            continue
        for repo in sorted(owner.iterdir()):
            rel = f"apps/{owner.name}/{repo.name}"
            if repo.is_symlink() or not repo.is_dir():
                problems.append(f"{rel} is {'a symlink' if repo.is_symlink() else 'not a directory'}; apps/ holds only apps/<owner>/<repo>/<env>")
                continue
            repos.setdefault(f"{owner.name}/{repo.name}".lower(), []).append(rel)
            for env in sorted(repo.iterdir()):
                rel = f"apps/{owner.name}/{repo.name}/{env.name}"
                if env.is_symlink():
                    problems.append(f"{rel} is a symlink")
                elif not env.is_dir() or env.name not in ENVIRONMENTS:
                    problems.append(f"{rel} is not an environment directory (test or prod)")
                else:
                    found.append(env)
    for paths in repos.values():
        if len(paths) > 1:
            problems.append(f"{' and '.join(paths)} are one repo under two cases")
    return found, problems


def verify_tree(root, expect_url: str | None = None) -> dict:
    """{"environments": n, "problems": [...]} for the whole deploy repo: every environment verified, the tree's shape, no two
    environments sharing a namespace (not even one app's test and prod: the convention is <repo>-<env>), and every environment's
    two adapters exactly as compose writes them, with no adapter left for an environment that is gone, and the whole repo off by
    default (golden_road.off_by_default). With `expect_url` (the workflows pass $GITHUB_SERVER_URL/$GITHUB_REPOSITORY), the Flux
    source's url must be this repository, and so must every adapter's (they are compared with what compose writes from it)."""
    environments, problems = find_environments(root)
    if expect_url is not None:
        try:
            check_repo_url(deploy_repo_url(root), expect_url)
        except InputError as exc:
            problems.append(str(exc))
    by_namespace, loaded = {}, {}
    for d in environments:
        problems.extend(verify_environment(d))
        try:
            loaded[d] = release = load_release(d)
        except (InputError, OSError):
            continue  # verify_environment reported it
        by_namespace.setdefault(release["namespace"], []).append(_rel(d))
    for namespace, users in sorted(by_namespace.items()):
        if len(users) > 1:
            problems.append(f"namespace {namespace} is used by more than one environment: {', '.join(users)}")
    problems.extend(_verify_adapters(Path(root), environments, loaded))
    problems.extend(off_by_default.problems(root))  # nothing reconciles or denies on its own, read from every YAML document
    return {"environments": len(environments), "problems": problems}


def pins(root) -> dict:
    """{"apps/<owner>/<repo>/<env>": release} for every environment, each release.yaml loaded and validated as load_release does.
    Refuses the whole tree (InputError) on anything under apps/ that is not an environment and on any release.yaml that does not
    load: the workflows that read the pins (deploy-check, bump) never act on part of a tree."""
    environments, problems = find_environments(root)
    if problems:
        raise InputError(problems[0][:300])
    out = {}
    for d in environments:
        try:
            out[_rel(d)] = load_release(d)
        except (InputError, OSError) as exc:
            raise InputError(f"{_rel(d)}: {exc}"[:300]) from None
    return out

# ---- a new pin, as bump.yml writes it ----

RELEASE_TAG = {env: re.compile(rf"^{env}-[0-9]{{14}}-[0-9a-f]{{7}}$") for env in ENVIRONMENTS}
MAX_GATE_RECORD_BYTES = 1_048_576


def plan_pin(root, rel: str, *, release: str, manifests, gate_record) -> dict:
    """{path: bytes} for one environment's release.yaml and base/manifests.yaml, from a published release's tag and its two assets,
    computed without writing. The gate record must be a passing gate-record/v1 for this repo whose manifests_sha256 is the
    manifests' sha256, and its release must be the tag (test) or a test release of the same commit (prod, whose gate record is the
    promoted one). The image is the gate record's. The namespace is kept from the current release.yaml, or for a new environment
    is default_namespace (which refuses a repo name that gives none: its namespace is then set by hand). Raises InputError."""
    d = environment_dir(root, rel)
    owner, name, environment = d.parts[-3:]
    repo = f"{owner}/{name}"
    for node in (d.parent.parent, d.parent, d, d / "base", d / "release.yaml", d / "base/manifests.yaml"):
        if node.is_symlink():
            raise InputError(f"{_rel(d)}: {node.relative_to(Path(root)).as_posix()} is a symlink")
    if not isinstance(release, str) or not RELEASE_TAG[environment].fullmatch(release):
        raise InputError(f"{release!r} is not a {environment} release tag ({environment}-YYYYMMDDHHMMSS-sha7)"[:300])
    raw = _read_capped(Path(manifests), MAX_FILE_BYTES, "manifests.yaml")
    try:
        record = json.loads(_read_capped(Path(gate_record), MAX_GATE_RECORD_BYTES, "gate-record.json").decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        raise InputError("gate-record.json is not JSON") from None
    errors = validate("gate-record.v1", record)
    if errors:
        raise InputError(f"gate-record.json is not a valid gate-record/v1: {errors[0]}"[:300])
    if record["status"] != "pass":
        raise InputError(f"the gate record of {release} did not pass")
    if record["repo"] != repo:
        raise InputError(f"the gate record is for {record['repo']}, not {repo}")
    if hashlib.sha256(raw).hexdigest() != record["manifests_sha256"]:
        raise InputError(f"the manifests.yaml of {release} does not match its gate record's manifests_sha256")
    tested = record["release"]
    if (environment == "test" and tested != release) or (environment == "prod" and tested[-7:] != release[-7:]):
        raise InputError(f"the gate record is {tested}'s, not a test release of {release}'s commit")
    namespace = load_release(d)["namespace"] if (d / "release.yaml").exists() else default_namespace(repo, environment)
    pin = {"schema": "deploy-release/v1", "repo": repo, "environment": environment, "namespace": namespace, "release": release,
           "image": record["image"], "manifests_sha256": record["manifests_sha256"],
           "gate_record_sha256": hashlib.sha256(Path(gate_record).read_bytes()).hexdigest()}
    errors = validate("deploy-release.v1", pin)
    if errors:
        raise InputError(f"the pin would not be a valid deploy-release/v1: {errors[0]}"[:300])
    header = f"# Written by the bump workflow from the published release {release}; the platform reviews the pull request.\n"
    return {d / "release.yaml": (header + yaml.safe_dump(pin, sort_keys=False)).encode("utf-8"), d / "base/manifests.yaml": raw}


def write_bytes_planned(planned: dict) -> list[Path]:
    """Write each file byte for byte (a temp file in the same directory, then a rename), creating its directory."""
    for path, data in planned.items():
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".golden-road-", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.chmod(tmp, 0o644)
            os.replace(tmp, path)
        except BaseException:
            os.unlink(tmp)
            raise
    return list(planned)

# ---- the controller adapters ----

def adapter_name(owner: str, repo: str, environment: str) -> str:
    """<owner>-<repo>-<env>, lowercased with . and _ turned into -. Longer than 63 characters, it is cut to 56 and given a - and the
    first 6 hex digits of the sha256 of owner/repo/env, so two long names that share a prefix stay apart."""
    full = re.sub(r"[._]", "-", f"{owner}-{repo}-{environment}".lower())
    if len(full) > 63:
        digest = hashlib.sha256(f"{owner}/{repo}/{environment}".encode("utf-8")).hexdigest()[:6]
        full = f"{full[:56].rstrip('-')}-{digest}"
    if not NAMESPACE.fullmatch(full):  # a real check, not an assert: it must hold under python -O too
        raise InputError(f"{owner}/{repo} {environment} gives no DNS-1123 adapter name ({full!r}); rename the repo"[:300])
    return full


def adapter_name_or_none(owner: str, repo: str, environment: str):
    """adapter_name, or None when it refuses the name (verify reports that environment on its own)."""
    try:
        return adapter_name(owner, repo, environment)
    except InputError:
        return None


def adapters(owner: str, repo: str, environment: str, namespace: str, *, repo_url: str) -> dict:
    """{path from the repo root: text} for one environment's two adapters: a Flux Kustomization that is suspended, and an Argo CD
    Application with no automated sync. `repo_url` is this deploy repo's URL, as clusters/home/flux/gitrepository.yaml names it."""
    if not all(isinstance(x, str) and NAME_PART.fullmatch(x) and x not in (".", "..") for x in (owner, repo)):
        raise InputError(f"{owner!r}/{repo!r} is not an owner and repo"[:300])
    if environment not in ENVIRONMENTS:
        raise InputError(f"{environment!r} is not an environment (test or prod)"[:300])
    if not isinstance(namespace, str) or not NAMESPACE.fullmatch(namespace):
        raise InputError(f"{namespace!r} is not a namespace (a DNS-1123 label)"[:300])
    if not isinstance(repo_url, str) or not DEPLOY_REPO_URL.fullmatch(repo_url):
        raise InputError(f"{repo_url!r} is not a golden-road-deploy URL, https://<host>/<org>/golden-road-deploy"[:300])
    name, path = adapter_name(owner, repo, environment), f"apps/{owner}/{repo}/{environment}"
    flux = {"apiVersion": "kustomize.toolkit.fluxcd.io/v1", "kind": "Kustomization",
            "metadata": {"name": name, "namespace": "flux-system"},
            "spec": {"suspend": True, "interval": "10m", "path": f"./{path}", "prune": True,
                     "sourceRef": {"kind": "GitRepository", "name": "golden-road-deploy"}, "targetNamespace": namespace}}
    argo = {"apiVersion": "argoproj.io/v1alpha1", "kind": "Application",
            "metadata": {"name": name, "namespace": "argocd"},
            "spec": {"project": "default", "source": {"repoURL": repo_url, "targetRevision": "main", "path": path},
                     "destination": {"server": "https://kubernetes.default.svc", "namespace": namespace}}}
    dump = lambda doc: yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)
    return {
        f"{FLUX_DIR}/{name}.yaml": ADAPTER_HEADER.format(what=f"The Flux adapter for {path}.",
                                                         how="suspend: true until a person runs flux resume on the cluster.") + dump(flux),
        f"{ARGO_DIR}/{name}.yaml": ADAPTER_HEADER.format(what=f"The Argo CD adapter for {path}.",
                                                         how="no automated sync; a person syncs it by hand.") + dump(argo),
    }


def deploy_repo_url(root) -> str:
    """This deploy repo's URL, from clusters/home/flux/gitrepository.yaml: a Flux GitRepository named golden-road-deploy that reads
    main of https://<host>/<org>/golden-road-deploy. Raises InputError otherwise."""
    root = Path(root)
    for node in (root / "clusters", root / "clusters/home", root / FLUX_DIR):
        if node.is_symlink():
            raise InputError(f"{GITREPOSITORY}: {node.relative_to(root).as_posix()} is a symlink")
    try:
        doc = _read_yaml(root / GITREPOSITORY, MAX_BINDING_BYTES, loader=UniqueKeyLoader, label=GITREPOSITORY)
    except OSError as exc:
        raise InputError(f"{GITREPOSITORY} can't be read: {exc.strerror}") from None
    spec, meta = doc.get("spec"), doc.get("metadata")
    if (doc.get("apiVersion"), doc.get("kind")) != ("source.toolkit.fluxcd.io/v1", "GitRepository") or not isinstance(meta, dict) \
            or meta.get("name") != "golden-road-deploy" or not isinstance(spec, dict) or spec.get("ref") != {"branch": "main"}:
        raise InputError(f"{GITREPOSITORY} must be the Flux GitRepository golden-road-deploy on branch main")
    url = spec.get("url")
    if not isinstance(url, str) or not DEPLOY_REPO_URL.fullmatch(url):
        raise InputError(f"{GITREPOSITORY}'s url is not https://<host>/<org>/golden-road-deploy")
    return url


def check_repo_url(url: str, expect_url: str) -> None:
    """Refuse a Flux source url that is not this repository's (`expect_url`, https://<host>/<owner>/<repo>, as the workflow's
    GITHUB_SERVER_URL and GITHUB_REPOSITORY give it). Host and owner compare without case, as GitHub's do; no .git suffix either
    side (DEPLOY_REPO_URL refuses one in the file). Raises InputError."""
    if not isinstance(expect_url, str) or not DEPLOY_REPO_URL.fullmatch(expect_url.lower()):
        raise InputError(f"the expected url {expect_url!r} is not https://<host>/<org>/golden-road-deploy"[:300])
    if url.lower() != expect_url.lower():
        raise InputError(f"{GITREPOSITORY}'s url {url} is not this repository, {expect_url}; every adapter would reconcile another repo"[:300])


def plan_adapters(root, d, repo_url: str) -> dict:
    """{path: text} for one environment directory's two adapters, from its release.yaml's namespace. Raises InputError."""
    d, root = Path(d), Path(root)
    owner, repo, env = d.parts[-3:]
    for node in (root / "clusters", root / "clusters/home", root / FLUX_DIR, root / "clusters/office", root / ARGO_DIR):
        if node.is_symlink() or (node.exists() and not node.is_dir()):
            raise InputError(f"{node.relative_to(root).as_posix()} must be a directory, not a symlink")
    name = adapter_name(owner, repo, env)
    others = [e for e in find_environments(root)[0] if e != d and adapter_name_or_none(*e.parts[-3:]) == name]
    if others:
        raise InputError(f"{_rel(d)} and {', '.join(_rel(e) for e in others)} have the same adapter name, {name}; compose writes "
                         "neither over the other: rename one repo or set its adapters by hand")
    try:
        release = load_release(d)
    except InputError as exc:
        raise InputError(f"{_rel(d)}: {exc}") from None
    return {root / rel: text for rel, text in adapters(owner, repo, env, release["namespace"], repo_url=repo_url).items()}


def _verify_adapters(root: Path, environments: list, loaded: dict) -> list[str]:
    """Problems with clusters/: an environment's adapter missing or not what compose writes, two environments with one adapter name,
    an adapter file for no environment, or a symlink. `loaded` maps an environment directory to its release (absent: refused)."""
    problems, owner_of = [], {}
    url = None
    if environments:
        try:
            url = deploy_repo_url(root)
        except InputError as exc:
            problems.append(f"{exc}; the adapters can't be checked")
    for d in environments:
        owner, repo, env = d.parts[-3:]
        try:
            name = adapter_name(owner, repo, env)
        except InputError as exc:
            problems.append(f"{_rel(d)}: {exc}")
            continue
        if name in owner_of:
            problems.append(f"{owner_of[name]} and {_rel(d)} have the same adapter name, {name}; rename one repo or set its adapters by hand")
            continue
        owner_of[name] = _rel(d)
        if url is None or d not in loaded:
            continue  # reported above, or by verify_environment
        try:
            want = adapters(owner, repo, env, loaded[d]["namespace"], repo_url=url)
        except InputError as exc:
            problems.append(f"{_rel(d)}: {exc}")
            continue
        for rel, text in want.items():
            path = root / rel
            if path.is_symlink():
                problems.append(f"{rel} is a symlink")
            elif not path.is_file():
                problems.append(f"{rel} is missing (the adapter for {_rel(d)}); run golden-road compose")
            elif path.stat().st_size != len(text.encode("utf-8")) or path.read_bytes() != text.encode("utf-8"):
                problems.append(f"{rel} differs from what golden-road compose writes for {_rel(d)}")
    for rel_dir, committed in ADAPTER_DIR_FILES.items():
        directory = root / rel_dir
        if any(node.is_symlink() for node in (root / "clusters", directory.parent, directory)):
            problems.append(f"{rel_dir} or a parent is a symlink")
            continue
        if not directory.is_dir():
            continue
        for path in sorted(directory.iterdir()):
            rel = f"{rel_dir}/{path.name}"
            if path.name in committed:
                if path.is_symlink() or not path.is_file():
                    problems.append(f"{rel} must be a regular file")
            elif not path.name.endswith(".yaml") or path.name[:-5] not in owner_of:
                problems.append(f"{rel} is an adapter for no environment in apps/; remove it")
    return problems
