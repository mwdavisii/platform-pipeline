import json
import shutil
import subprocess

import pytest

from builder.config import load_base_images
from builder.render.dockerfile import dockerignore, render_dockerfile

IMAGES = load_base_images()


def cmd(text):
    line = next(l for l in text.splitlines() if l.startswith("CMD "))
    return json.loads(line[4:])


def test_python_uvicorn_with_authz(notes_spec, python_app):
    text = render_dockerfile(notes_spec, python_app, "0.1.0", IMAGES)
    assert text.startswith("# Generated by builder 0.1.0.")
    assert "pip install --require-hashes -r requirements.txt" in text
    assert "USER 10001:10001" in text
    assert cmd(text) == ["python", "-m", "uvicorn", "_platform.entry:app", "--host", "0.0.0.0", "--port", "8080"]
    assert all("@sha256:" in l for l in text.splitlines() if l.startswith("FROM "))


def test_python_without_authz_runs_entrypoint(notes_spec, python_app):
    del notes_spec["authz"]
    assert cmd(render_dockerfile(notes_spec, python_app, "0.1.0", IMAGES))[3] == "app:app"


def test_python_gunicorn(notes_spec, python_app):
    notes_spec["server"] = "gunicorn"
    assert cmd(render_dockerfile(notes_spec, python_app, "0.1.0", IMAGES)) == ["python", "-m", "gunicorn", "--header-map", "refuse", "--bind", "0.0.0.0:8080", "_platform.entry:app"]


def test_python_file_entrypoint(notes_spec, python_app):
    notes_spec["entrypoint"] = "main.py"
    del notes_spec["server"], notes_spec["authz"]
    assert cmd(render_dockerfile(notes_spec, python_app, "0.1.0", IMAGES)) == ["python", "main.py"]


def test_node_with_authz_preloads_guard(node_spec, node_app):
    text = render_dockerfile(node_spec, node_app, "0.1.0", IMAGES)
    assert "npm ci --omit=dev --ignore-scripts" in text
    assert "USER 65532:65532" in text
    assert cmd(text) == ["--require", "./_platform/authz.js", "server.js"]


def test_static_with_build(make_app):
    root = make_app({"package.json": '{"scripts": {"build": "vite build"}}'})
    spec = {"app_type": "static", "entrypoint": "dist", "port": 8080}
    text = render_dockerfile(spec, root, "0.1.0", IMAGES)
    assert "RUN npm run build" in text
    assert "COPY --from=build /app/dist/ /usr/share/nginx/html/" in text
    assert "USER 101:101" in text


def test_static_plain(make_app):
    root = make_app({"index.html": ""})
    text = render_dockerfile({"app_type": "static", "entrypoint": ".", "port": 8080}, root, "0.1.0", IMAGES)
    assert "npm" not in text
    assert "COPY ./ /usr/share/nginx/html/" in text


def test_dockerignore_excludes_secrets_and_state_at_any_depth(notes_spec, python_app):
    text = dockerignore(notes_spec, python_app)
    lines = text.splitlines()
    for entry in ("**/.env", "**/.env.*", "**/*.pem", "**/*.key", "**/*.p12", "**/*.pfx", "**/id_rsa*", "**/.npmrc",
                  "**/.pypirc", "**/.netrc", "**/.aws", "**/.ssh", "**/secrets", "**/__pycache__", "**/*.pyc", "**/node_modules"):
        assert entry in lines
    for entry in (".git", ".github", ".venv", "venv", "deploy", "Dockerfile", ".dockerignore", "builder-spec.json", ".builder.lock"):
        assert entry in lines
    assert "*.crt" not in text and "**/*.crt" not in text
    assert "_platform" not in text
    assert "package.json" not in lines


def test_dockerignore_static_without_build_hides_project_files(make_app):
    root = make_app({"index.html": ""})
    lines = dockerignore({"app_type": "static", "entrypoint": ".", "port": 8080}, root).splitlines()
    for entry in ("package.json", "package-lock.json", "*.md", ".gitignore"):
        assert entry in lines


def test_dockerignore_static_with_build_keeps_package_files(make_app):
    root = make_app({"package.json": '{"scripts": {"build": "vite build"}}'})
    lines = dockerignore({"app_type": "static", "entrypoint": "dist", "port": 8080}, root).splitlines()
    assert "package.json" not in lines
    assert "**/.npmrc" in lines


@pytest.mark.docker
@pytest.mark.skipif(shutil.which("docker") is None, reason="docker not installed")
def test_dockerignore_nested_secrets_absent_from_a_real_image(make_app):
    base = IMAGES["python"]["runtime"]
    spec = {"app_type": "python"}
    root = make_app({
        "keep.txt": "x",
        "config/.env": "SECRET=1",
        "certs/server.key": "k",
        "certs/ca.crt": "public",
        "deep/er/.npmrc": "token",
        "Dockerfile": f"FROM {base}\nCOPY . /ctx\n",
        ".dockerignore": dockerignore(spec, make_app({}, name="empty")),
    })
    if subprocess.run(["docker", "image", "inspect", base], capture_output=True).returncode != 0:
        pytest.skip("pinned python runtime image is not available locally")
    tag = "builder-dockerignore-test"
    subprocess.run(["docker", "build", "--network", "none", "-q", "-t", tag, str(root)], check=True, capture_output=True, timeout=300)
    try:
        listing = "import os; print(sorted(os.path.relpath(os.path.join(d, f), '/ctx') for d, _, fs in os.walk('/ctx') for f in fs))"
        out = subprocess.run(["docker", "run", "--rm", "--network", "none", tag, "python", "-c", listing],
                             check=True, capture_output=True, text=True, timeout=120)
    finally:
        subprocess.run(["docker", "rmi", "-f", tag], capture_output=True)
    files = eval(out.stdout)  # noqa: S307 - our own printed list of strings
    assert "keep.txt" in files and "certs/ca.crt" in files
    assert not [f for f in files if f.endswith((".env", ".key", ".npmrc"))]
