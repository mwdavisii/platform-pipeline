import copy

import yaml

from builder.config import load_platform
from builder.render.k8s import RESOURCES, render_k8s

PLATFORM = load_platform()


def docs(spec, uid=10001):
    return {path.rsplit("/", 1)[1]: yaml.safe_load(text) for path, text in render_k8s(spec, PLATFORM, uid).items()}


def test_files_and_kustomization(notes_spec):
    out = render_k8s(notes_spec, PLATFORM, 10001)
    assert sorted(out) == sorted(f"deploy/base/{n}" for n in [*RESOURCES, "kustomization.yaml"])
    assert all(text.startswith("# Generated by builder.") for text in out.values())
    assert docs(notes_spec)["kustomization.yaml"]["resources"] == RESOURCES


def test_pod_security_standards_restricted(notes_spec):
    pod = docs(notes_spec)["deployment.yaml"]["spec"]["template"]["spec"]
    assert pod["automountServiceAccountToken"] is False
    assert pod["securityContext"]["runAsNonRoot"] is True
    assert pod["securityContext"]["runAsUser"] == 10001
    assert pod["securityContext"]["seccompProfile"] == {"type": "RuntimeDefault"}
    [container] = pod["containers"]
    sc = container["securityContext"]
    assert sc["allowPrivilegeEscalation"] is False
    assert sc["readOnlyRootFilesystem"] is True
    assert sc["capabilities"] == {"drop": ["ALL"]}
    assert {"name": "tmp", "mountPath": "/tmp"} in container["volumeMounts"]


def test_resources_probes_and_env(notes_spec):
    [container] = docs(notes_spec)["deployment.yaml"]["spec"]["template"]["spec"]["containers"]
    assert container["resources"] == PLATFORM["resources_tiers"]["default"]
    assert container["readinessProbe"]["httpGet"] == {"path": "/healthz", "port": "http"}
    assert {"name": "PORT", "value": "8080"} in container["env"]
    assert {"name": "NOTES_DB_URL", "valueFrom": {"secretKeyRef": {"name": "notes-api-secrets", "key": "NOTES_DB_URL"}}} in container["env"]


def test_tcp_probe_without_health_path(notes_spec):
    del notes_spec["health_path"]
    [container] = docs(notes_spec)["deployment.yaml"]["spec"]["template"]["spec"]["containers"]
    assert container["livenessProbe"]["tcpSocket"] == {"port": "http"}


def test_ingress_only_from_edge_and_default_deny_egress(notes_spec):
    np = docs(notes_spec)["networkpolicy.yaml"]
    assert np["spec"]["policyTypes"] == ["Ingress", "Egress"]
    assert np["spec"]["egress"] == []
    [rule] = np["spec"]["ingress"]
    [peer] = rule["from"]
    assert peer["namespaceSelector"]["matchLabels"] == {"kubernetes.io/metadata.name": "cloudflared"}
    assert peer["podSelector"]["matchLabels"] == {"app": "cloudflared"}


def test_cilium_egress_allows_dns_and_declared_hosts(notes_spec):
    cnp = docs(notes_spec)["cilium-egress.yaml"]
    assert cnp["kind"] == "CiliumNetworkPolicy"
    dns, gateway = cnp["spec"]["egress"]
    assert dns["toPorts"][0]["rules"] == {"dns": [{"matchPattern": "*"}]}
    assert gateway["toFQDNs"] == [{"matchName": "litellm.internal"}]
    assert gateway["toPorts"] == [{"ports": [{"port": "443", "protocol": "TCP"}]}]


def test_dns_rule_selects_the_cluster_dns_pods(notes_spec):
    dns = docs(notes_spec)["cilium-egress.yaml"]["spec"]["egress"][0]
    assert dns["toEndpoints"] == [{"matchLabels": {"io.kubernetes.pod.namespace": "kube-system", "k8s-app": "kube-dns"}}]
    assert dns["toPorts"][0]["ports"] == [{"port": "53", "protocol": "ANY"}]


def test_ingress_port_is_the_named_container_port(notes_spec):
    docs_ = docs(notes_spec)
    [rule] = docs_["networkpolicy.yaml"]["spec"]["ingress"]
    assert rule["ports"] == [{"protocol": "TCP", "port": "http"}]
    [container] = docs_["deployment.yaml"]["spec"]["template"]["spec"]["containers"]
    assert container["ports"][0]["name"] == "http"


def test_deployment_has_no_yaml_anchors(notes_spec):
    text = render_k8s(notes_spec, PLATFORM, 10001)["deploy/base/deployment.yaml"]
    assert "&id" not in text
    assert "*id" not in text
    assert not any(token.startswith(("&", "*")) for line in text.splitlines() for token in line.split() if len(token) > 1)


def test_in_cluster_hosts_use_endpoint_rules(notes_spec):
    platform = copy.deepcopy(PLATFORM)
    platform["in_cluster_egress"] = {"qdrant.internal": {"namespace": "data", "pod_labels": {"app": "qdrant"}, "port": 6333}}
    notes_spec["egress"].append({"host": "qdrant.internal", "port": 443, "reason": "vector search"})
    egress = yaml.safe_load(render_k8s(notes_spec, platform, 10001)["deploy/base/cilium-egress.yaml"])["spec"]["egress"]
    assert len(egress) == 3
    [qdrant] = [rule for rule in egress if "toFQDNs" not in rule and rule is not egress[0]]
    assert qdrant["toEndpoints"] == [{"matchLabels": {"io.kubernetes.pod.namespace": "data", "app": "qdrant"}}]
    assert qdrant["toPorts"] == [{"ports": [{"port": "6333", "protocol": "TCP"}]}]
    assert {"matchName": "litellm.internal"} in [f for rule in egress for f in rule.get("toFQDNs", [])]
    assert all("qdrant.internal" not in str(rule) for rule in egress)


def test_hosts_outside_the_in_cluster_map_still_use_fqdns(notes_spec):
    platform = copy.deepcopy(PLATFORM)
    platform["in_cluster_egress"] = {"qdrant.internal": {"namespace": "data", "pod_labels": {"app": "qdrant"}, "port": 6333}}
    egress = yaml.safe_load(render_k8s(notes_spec, platform, 10001)["deploy/base/cilium-egress.yaml"])["spec"]["egress"]
    assert egress[1]["toFQDNs"] == [{"matchName": "litellm.internal"}]


def test_platform_without_in_cluster_map_still_renders(notes_spec):
    platform = {k: v for k, v in PLATFORM.items() if k != "in_cluster_egress"}
    assert "toFQDNs" in yaml.safe_load(render_k8s(notes_spec, platform, 10001)["deploy/base/cilium-egress.yaml"])["spec"]["egress"][1]


def test_no_egress_means_dns_only(notes_spec):
    notes_spec["egress"] = []
    assert len(docs(notes_spec)["cilium-egress.yaml"]["spec"]["egress"]) == 1
