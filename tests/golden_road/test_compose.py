def docs(text):
    return [o for o in yaml.safe_load_all(text) if o]


def edited(signed, fn):
    objects = docs(signed)
    fn(objects)
    return "---\n".join(yaml.safe_dump(o, sort_keys=False) for o in objects)


def test_no_binding_composes_to_the_signed_objects(signed):
    objects = parse_manifests(signed, IMAGE)
    assert [o["kind"] for o in objects] == ["ServiceAccount", "Deployment", "Service", "NetworkPolicy", "CiliumNetworkPolicy"]
    out = compose(signed, IMAGE, None)
    assert docs(out) == objects
    assert out.startswith("# Generated by golden-road compose")


def test_a_binding_adds_the_identity_env_and_egress(signed):
    out = docs(compose(signed, IMAGE, {"azure_identity": IDENTITY}))
    assert out[0]["metadata"]["annotations"]["azure.workload.identity/client-id"] == IDENTITY["client_id"]
    assert out[1]["spec"]["template"]["metadata"]["labels"]["azure.workload.identity/use"] == "true"
    env = {e["name"]: e["value"] for e in out[1]["spec"]["template"]["spec"]["containers"][0]["env"] if "value" in e}
