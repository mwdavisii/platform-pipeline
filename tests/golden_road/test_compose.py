def _only_replicas_differ(before, after):
    """The two composed documents are the same but for the Deployment's spec.replicas."""
    a, b = docs(before), docs(after)
    assert len(a) == len(b)
    for x, y in zip(a, b):
        if x["kind"] == "Deployment":
            x, y = {**x, "spec": {k: v for k, v in x["spec"].items() if k != "replicas"}}, {**y, "spec": {k: v for k, v in y["spec"].items() if k != "replicas"}}
        assert x == y


@pytest.mark.parametrize("binding", [None, BINDING])
def test_a_suspended_environment_runs_no_pods_and_keeps_everything_else(signed, binding):
    running = compose(signed, IMAGE, binding, namespace="notes-test")
    suspended = compose(signed, IMAGE, binding, namespace="notes-test", lifecycle=SUSPENDED)
    deployment = next(o for o in docs(suspended) if o["kind"] == "Deployment")
    assert deployment["spec"]["replicas"] == 0
    assert next(o for o in docs(running) if o["kind"] == "Deployment")["spec"]["replicas"] == 1
    _only_replicas_differ(running, suspended)
    assert suspended.startswith("# Generated by golden-road compose from base/manifests.yaml and bindings.yaml.")


