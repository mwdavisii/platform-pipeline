@pytest.mark.parametrize("where", ["metadata:\n  name: notes-api\n", "kind: ServiceAccount\n"])
def test_duplicate_keys_are_refused(signed, where):
    # PyYAML keeps the last of two equal keys; a reviewer reading base/manifests.yaml might see the first. Neither is guessed at.
    first, rest = signed.split("kind: ServiceAccount\n", 1)
    text = first + "kind: ServiceAccount\n" + where + rest
    with pytest.raises(ComposeError, match="duplicate key"):
        parse_manifests(text, IMAGE)


