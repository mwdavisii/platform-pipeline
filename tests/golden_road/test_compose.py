SECRET = {"env": "NOTES_DB_PASSWORD", "secret_id": 1042, "secret_name": "notes-db", "folder_id": 17, "field_slug": "password",
          "verified_by": "mock-secret-server"}


def external_secret_for(app, data):
    return {"apiVersion": "external-secrets.io/v1", "kind": "ExternalSecret", "metadata": {"name": f"{app}-delinea"},
            "spec": {"refreshInterval": "1h", "secretStoreRef": {"kind": "ClusterSecretStore", "name": EXTERNAL_SECRET_STORE},
                     "target": {"name": f"{app}-delinea", "creationPolicy": "Owner"}, "data": data}}


def test_secrets_become_one_external_secret_and_secret_key_refs(signed):
    out = docs(compose(signed, IMAGE, {"secrets": [SECRET]}, namespace="notes-test"))
    assert [o["kind"] for o in out] == ["Namespace", "ServiceAccount", "Deployment", "Service", "NetworkPolicy",
                                        "CiliumNetworkPolicy", "ExternalSecret"]
    app = out[2]["metadata"]["name"]
    assert EXTERNAL_SECRET_STORE == "delinea-secret-server"
    assert out[-1] == external_secret_for(app, [{"secretKey": "NOTES_DB_PASSWORD", "remoteRef": {"key": "1042", "property": "password"}}])
    env = out[2]["spec"]["template"]["spec"]["containers"][0]["env"]
    assert {"name": "NOTES_DB_PASSWORD", "valueFrom": {"secretKeyRef": {"name": f"{app}-delinea", "key": "NOTES_DB_PASSWORD"}}} in env
    assert "azure.workload.identity/client-id" not in str(out)  # secrets switch no identity on


def test_secrets_and_an_identity_compose_together_in_env_name_order(signed):
    second = {**SECRET, "env": "A_TOKEN", "secret_id": 7, "field_slug": "token"}
    out = docs(compose(signed, IMAGE, {**BINDING, "secrets": [SECRET, second]}))
    env = [e["name"] for e in out[1]["spec"]["template"]["spec"]["containers"][0]["env"]]
    assert env.index("DATABRICKS_SCHEMA") < env.index("A_TOKEN") < env.index("NOTES_DB_PASSWORD")
    assert [d["secretKey"] for d in out[-1]["spec"]["data"]] == ["A_TOKEN", "NOTES_DB_PASSWORD"]
    assert out[0]["metadata"]["annotations"]["azure.workload.identity/client-id"] == IDENTITY["client_id"]


